// Runs the venue relay and its settlement worker on this machine, as venue hardware would, for the
// physical Android terminal.
//
//   node scripts/venue-relay-local.mjs setup   # keys, TLS, terminal snapshot, enrollment QR
//   node scripts/venue-relay-local.mjs start   # relay (HTTPS) + settlement worker + adb reverse
//
// The terminal reaches the relay at https://localhost:3003 through `adb reverse`, so the link works
// with Wi-Fi off. TLS uses a local CA whose name constraints allow only `localhost`; `setup` places
// its certificate in a gitignored debug resource overlay, so only debug builds trust it, and only
// for localhost. Everything else stays under the gitignored `secrets/testnet/venue-relay/`.

import { execFileSync, spawn } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const secrets = join(root, "secrets", "testnet");
const dir = join(secrets, "venue-relay");
const deployments = join(root, "deployments", "testnet");
const debugRes = join(root, "apps", "terminal-android", "app", "src", "debug", "res");
const port = 3003;
const audience = `https://localhost:${port}/v1/vouchers`;

process.loadEnvFile(process.env.OPENBALANCE_ENV_FILE ?? join(root, ".env.testnet"));
const rpcUrl = process.env.ACCOUNT_RPC_URL;
if (!rpcUrl?.startsWith("https://")) throw new Error("ACCOUNT_RPC_URL must be an https URL");

const provisioning = JSON.parse(readFileSync(join(deployments, "event-provisioning.json"), "utf8"));
const terminal = JSON.parse(
  readFileSync(join(deployments, "device-terminal-provisioning.json"), "utf8"),
);
const financial = JSON.parse(
  readFileSync(join(deployments, "financial-manifest.json"), "utf8"),
).events.find((event) => event.eventId === provisioning.eventId);
if (!financial) throw new Error("financial-manifest.json does not contain the provisioned event");

const path = (name) => join(dir, name);
const openssl = (...args) => execFileSync("openssl", args, { stdio: ["ignore", "ignore", "pipe"] });

async function rpc(method, params) {
  const response = await fetch(rpcUrl, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }),
  });
  const body = await response.json();
  if (body.error) throw new Error(`${method} failed: ${body.error.message}`);
  return body.result;
}

function tls() {
  if (existsSync(path("server.pem"))) return;
  // A private CA limited to `localhost`: even if its key leaked it could not vouch for any other
  // name, and only debug builds trust it at all.
  writeFileSync(
    path("ca.cnf"),
    [
      "[req]",
      "distinguished_name=dn",
      "x509_extensions=ca",
      "prompt=no",
      "[dn]",
      "CN=OpenBalance local venue relay CA",
      "[ca]",
      "basicConstraints=critical,CA:TRUE,pathlen:0",
      "keyUsage=critical,keyCertSign,cRLSign",
      "nameConstraints=critical,permitted;DNS:localhost,permitted;IP:127.0.0.1/255.255.255.255",
      "subjectKeyIdentifier=hash",
      "",
    ].join("\n"),
  );
  writeFileSync(
    path("server.cnf"),
    [
      "basicConstraints=critical,CA:FALSE",
      "keyUsage=critical,digitalSignature",
      "extendedKeyUsage=serverAuth",
      "subjectAltName=DNS:localhost,IP:127.0.0.1",
      "",
    ].join("\n"),
  );
  openssl("ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", path("ca.key"));
  openssl(
    "req",
    "-new",
    "-x509",
    "-key",
    path("ca.key"),
    "-days",
    "90",
    "-config",
    path("ca.cnf"),
    "-out",
    path("ca.pem"),
  );
  openssl("ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", path("server.key"));
  openssl(
    "req",
    "-new",
    "-key",
    path("server.key"),
    "-subj",
    "/CN=localhost",
    "-out",
    path("server.csr"),
  );
  openssl(
    "x509",
    "-req",
    "-in",
    path("server.csr"),
    "-CA",
    path("ca.pem"),
    "-CAkey",
    path("ca.key"),
    "-CAcreateserial",
    "-days",
    "30",
    "-extfile",
    path("server.cnf"),
    "-out",
    path("server.pem"),
  );
}

function debugOverlay() {
  mkdirSync(join(debugRes, "raw"), { recursive: true });
  mkdirSync(join(debugRes, "xml"), { recursive: true });
  writeFileSync(join(debugRes, "raw", "venue_relay_ca.pem"), readFileSync(path("ca.pem")));
  writeFileSync(
    join(debugRes, "xml", "network_security_config.xml"),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/venue-relay-local.mjs; debug builds only, gitignored. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="false">
        <domain includeSubdomains="false">localhost</domain>
        <trust-anchors>
            <certificates src="@raw/venue_relay_ca" />
        </trust-anchors>
    </domain-config>
</network-security-config>
`,
  );
}

async function snapshot() {
  const block = await rpc("eth_getBlockByNumber", ["finalized", false]);
  const now = Math.floor(Date.now() / 1_000);
  // Every reserve channel opened for this terminal that the vault still holds open.
  const channels = new Set();
  const channelFile = join(secrets, "device-channel.json");
  if (existsSync(channelFile))
    channels.add(JSON.parse(readFileSync(channelFile, "utf8")).channelId);
  for (const extra of (process.env.VENUE_RELAY_EXTRA_CHANNELS ?? "").split(",").filter(Boolean))
    channels.add(extra);
  const terminalCall = await rpc("eth_call", [
    {
      to: terminal.registry,
      // terminals(bytes32,uint256) -> (vendorId, signer, validAfter, validUntil, enabled)
      data: `0x8eb0f0fc${terminal.terminalId.slice(2)}${terminal.terminalVersion.toString(16).padStart(64, "0")}`,
    },
    "finalized",
  ]);
  // The relay authorizes exactly what the registry records at finality, never local assumptions.
  const word = (index) => BigInt(`0x${terminalCall.slice(2 + 64 * index, 2 + 64 * (index + 1))}`);
  if (terminalCall.length < 2 + 64 * 5 || word(4) !== 1n)
    throw new Error("Device terminal is not registered and enabled at the finalized block");
  if (
    `0x${terminalCall.slice(2 + 64 + 24, 2 + 128)}`.toLowerCase() !==
    terminal.terminalSigner.toLowerCase()
  )
    throw new Error("Registry terminal signer does not match device-terminal-provisioning.json");
  const validAfter = Number(word(2));
  const validUntil = Number(word(3));
  writeFileSync(
    path("terminals.json"),
    JSON.stringify({
      schemaVersion: 1,
      chainId: terminal.chainId,
      registry: terminal.registry,
      vault: financial.vault,
      finalizedBlockNumber: BigInt(block.number).toString(),
      finalizedBlockHash: block.hash,
      generatedAt: now,
      expiresAt: Math.min(validUntil, now + 12 * 3_600),
      terminals: [...channels].map((channelId) => ({
        terminalId: terminal.terminalId,
        keyVersion: String(terminal.terminalVersion),
        channelId,
        signer: terminal.terminalSigner,
        enabled: true,
        validAfter,
        validUntil,
      })),
    }),
    { mode: 0o600 },
  );
  return channels.size;
}

async function enrollmentQr() {
  // Same credential and API as the current enrollment; only the relay endpoint moves to this host.
  const current = await import(join(root, "packages", "scenario", "dist", "attendee-signer.js"));
  const existing = current.decodeQrPng(readFileSync(join(secrets, "terminal-enrollment-qr.png")));
  const config = JSON.parse(Buffer.from(existing.replace(/^obterm2:/, ""), "base64url").toString());
  // The terminal compares the payload byte for byte with Android's `JSONObject.toString()`, which
  // escapes every `/` as `\/`; plain JSON.stringify output is rejected as non-canonical.
  const canonical = JSON.stringify({
    schemaVersion: 2,
    apiEndpoint: config.apiEndpoint,
    rpcEndpoint: config.rpcEndpoint,
    relayEndpoint: audience,
    accessToken: config.accessToken,
  }).replaceAll("/", "\\/");
  const { default: QRCode } = await import(
    join(root, "packages", "scenario", "node_modules", "qrcode", "lib", "index.js")
  );
  await QRCode.toFile(
    path("enrollment-qr.png"),
    `obterm2:${Buffer.from(canonical).toString("base64url")}`,
    {
      errorCorrectionLevel: "M",
      margin: 4,
      width: 720,
    },
  );
}

async function setup() {
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  if (!existsSync(path("relay.key")))
    writeFileSync(
      path("relay.key"),
      execFileSync("openssl", ["rand", "-hex", "32"]).toString().trim(),
      { mode: 0o600 },
    );
  writeFileSync(
    path("settlement.key"),
    readFileSync(join(secrets, "harness-signer"), "utf8").trim(),
    { mode: 0o600 },
  );
  tls();
  debugOverlay();
  const count = await snapshot();
  await enrollmentQr();
  process.stdout.write(
    `${JSON.stringify({ audience, channels: count, enrollmentQr: path("enrollment-qr.png"), debugOverlay: debugRes })}\n`,
  );
}

function start() {
  execFileSync("adb", ["reverse", `tcp:${port}`, `tcp:${port}`], { stdio: "inherit" });
  const relayDir = join(root, "services", "venue-relay");
  const common = {
    PATH: process.env.PATH,
    VENUE_RELAY_DATABASE_PATH: path("relay.sqlite"),
    VENUE_RELAY_KEY_PATH: path("relay.key"),
  };
  const redact = (text) => text.replaceAll(rpcUrl, "<rpc>");
  const run = (name, entry, env) => {
    const child = spawn(process.execPath, [join(relayDir, "dist", entry)], { cwd: relayDir, env });
    for (const stream of [child.stdout, child.stderr])
      stream.on("data", (chunk) => process.stdout.write(`[${name}] ${redact(String(chunk))}`));
    child.on("exit", (code) => process.stdout.write(`[${name}] exited ${code}\n`));
    return child;
  };
  const children = [
    run("relay", "server.js", {
      ...common,
      HOST: "127.0.0.1",
      PORT: String(port),
      METRICS_PORT: "9466",
      TERMINAL_SNAPSHOT_PATH: path("terminals.json"),
      TERMINAL_INGRESS_AUDIENCE: audience,
      VENUE_RELAY_TLS_CERT_PATH: path("server.pem"),
      VENUE_RELAY_TLS_KEY_PATH: path("server.key"),
    }),
    run("settle", "settlement-worker-server.js", {
      ...common,
      METRICS_PORT: "9467",
      VENUE_RELAY_RPC_URL: rpcUrl,
      VENUE_RELAY_CHAIN_ID: String(terminal.chainId),
      VENUE_RELAY_CHAIN_NAME: "Monad Testnet",
      VENUE_RELAY_VAULT_ADDRESS: financial.vault,
      VENUE_RELAY_DEPLOYMENT_BLOCK: String(financial.deploymentBlock),
      VENUE_RELAY_SETTLEMENT_PRIVATE_KEY_PATH: path("settlement.key"),
      VENUE_RELAY_SETTLEMENT_WORKER_ID: "laptop-venue-relay",
    }),
  ];
  for (const signal of ["SIGINT", "SIGTERM"])
    process.once(signal, () => {
      for (const child of children) child.kill("SIGTERM");
    });
}

const command = process.argv[2];
if (command === "setup") await setup();
else if (command === "start") start();
else {
  process.stderr.write("Usage: venue-relay-local.mjs <setup|start>\n");
  process.exit(64);
}
